# Student Grade Evaluation using elif ladder
marks = float(input("Enter the student's marks: "))

if marks >= 90:
    grade = "A"
elif marks >= 80:
    grade = "B"
elif marks >= 70:
    grade = "C"
elif marks >= 60:
    grade = "D"
else:
    grade = "F"

print(f"The student's grade is: {grade}")